/**
 * Returns assessment questions filtered strictly by subject and grade.
 * Uses robust Kurdish and English subject alias resolution.
 * If no questions match the subject, returns an empty array to prevent subject mixing.
 */
export function getQuestionsBySubject(subject: string, grade = 12): AssessmentQuestionItem[] {
  const targetKey = normalizeSubjectKey(subject);
  return REAL_ASSESSMENT_QUESTIONS.filter(
    (q) =>
      normalizeSubjectKey(q.subject) === targetKey &&
      (!grade || q.grade === Number(grade))
  );
}
